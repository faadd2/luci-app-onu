def po_escape(s):
    return s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n')

lines = []
lines.append('msgid ""')
lines.append('msgstr ""')
lines.append('"Content-Type: text/plain; charset=UTF-8\\n"')
lines.append('')
for s in ids:
    lines.append('msgid "%s"' % po_escape(s))
    zh = ZH.get(s, '')
    lines.append('msgstr "%s"' % po_escape(zh))
    lines.append('')

