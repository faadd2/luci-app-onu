print('po written:', os.path.join(outdir, 'pon.po'))

# 生成 zh-inline JS（无 lmo 环境下直接把 _('x') 替换为 '译文'）
outjs = os.path.join(BASE, '_zh_inline')
os.makedirs(outjs, exist_ok=True)
pat = re.compile(r"_\('((?:[^'\\]|\\.)*)'\)")

def repl(m):
    raw = m.group(1)
    s = raw.replace("\\'", "'").replace('\\n', '\n')
    zh = ZH.get(s)
    if zh is None:
        return m.group(0)
    new = zh.replace('\\', '\\\\').replace("'", "\\'")
    return "'%s'" % new

for f in glob.glob('*.js'):
    src = open(f, encoding='utf-8').read()
    dst = pat.sub(repl, src)
    open(os.path.join(outjs, f), 'w', encoding='utf-8').write(dst)
print('zh-inline js written to', outjs)
